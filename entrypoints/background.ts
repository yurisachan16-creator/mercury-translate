function pdfRequestKey(documentFingerprint: string, pageIndex: number): string {
    return `${documentFingerprint}:${pageIndex}`;
}

function cancelPdfRequests(documentFingerprint: string, pageIndex?: number): void {
    if (typeof pageIndex === 'number') {
        const key = pdfRequestKey(documentFingerprint, pageIndex);
        pdfCancellationGeneration.set(key, (pdfCancellationGeneration.get(key) || 0) + 1);
        return;
    }

    const prefix = `${documentFingerprint}:`;
    for (const key of pdfCancellationGeneration.keys()) {
        if (key.startsWith(prefix)) {
            pdfCancellationGeneration.set(key, (pdfCancellationGeneration.get(key) || 0) + 1);
        }
    }
}

function assertPdfRequestActive(key: string, generation: number): void {
    if ((pdfCancellationGeneration.get(key) || 0) !== generation) {
        const error = new Error('PDF translation cancelled');
        error.name = 'AbortError';
        throw error;
    }
}

function isPdfTranslationRequest(value: unknown): value is PdfTranslationRequest {
    if (!value || typeof value !== 'object') return false;
    const request = value as Partial<PdfTranslationRequest>;
    return typeof request.documentFingerprint === 'string'
        && Number.isInteger(request.pageIndex)
        && Number(request.pageIndex) >= 0
        && typeof request.sourceLanguage === 'string'
        && typeof request.targetLanguage === 'string'
        && Array.isArray(request.segments)
        && request.segments.length <= 500
        && request.segments.every(segment => Boolean(segment)
            && typeof segment.id === 'string'
            && typeof segment.text === 'string'
            && typeof segment.contentHash === 'string');
}

async function fetchImageForOcr(source: string): Promise<string> {
    const url = normalizeRemoteImageUrl(source);
    const response = await fetch(url, { credentials: 'omit', redirect: 'follow' });
    if (!response.ok) {
        throw new Error(`图片服务器返回 ${response.status}`);
    }

    const contentType = response.headers.get('content-type') || '';
    const contentLength = Number(response.headers.get('content-length') || 0);
    if (contentLength > MAX_REMOTE_IMAGE_BYTES) {
        throw new Error('图片文件过大');
    }

    const buffer = await response.arrayBuffer();
    return imageBufferToDataUrl(buffer, contentType);
}

